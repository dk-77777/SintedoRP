import {chromium} from '@playwright/test';
import {previewState} from './preview-data';
import {mkdir} from 'node:fs/promises';
await mkdir('artifacts/cinematic-v6/review',{recursive:true});
const b=await chromium.launch({executablePath:'/usr/bin/chromium'});
const p=await b.newPage({viewport:{width:1440,height:1000}});
await p.route('**/api/**',r=>r.fulfill({contentType:'application/json',body:JSON.stringify(previewState('publico'))}));
p.on('pageerror',e=>console.log('PAGE ERROR',e.message));
await p.goto('http://localhost:3000');await p.waitForTimeout(2400);await p.screenshot({path:'artifacts/cinematic-v6/review/home-desktop.png',fullPage:true});
await p.setViewportSize({width:390,height:844});await p.goto('http://localhost:3000');await p.waitForTimeout(2200);await p.screenshot({path:'artifacts/cinematic-v6/review/home-mobile.png',fullPage:true});
await p.setViewportSize({width:1440,height:1000});await p.goto('http://localhost:3000/entrar');await p.waitForTimeout(1600);await p.screenshot({path:'artifacts/cinematic-v6/review/login.png',fullPage:true});
await b.close();
